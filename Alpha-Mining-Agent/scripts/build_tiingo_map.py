"""Propose Tiingo entities for index tickers yfinance cannot serve.

Reads the coverage report of the first, yfinance-only download and Tiingo's public supported_tickers list and
writes data/tiingo_map.csv: one row per index ticker whose entity is missing on
yfinance and that Tiingo lists over the whole membership span. Tickers already
in data/ticker_map.csv are left to that file. Review the output by hand.
"""
import pandas as pd

from alpha_mining.config import DATA_RAW, ROOT, TRAIN, data_end
from alpha_mining.data.universe import TICKER_MAP_FILE, index_membership

YF_ONLY_REPORT = ROOT / "data" / "coverage_report_yfinance_only.csv"  # first, yfinance-only pass
TIINGO_LIST = DATA_RAW / "tiingo" / "supported_tickers.csv"
OUT = ROOT / "data" / "tiingo_map.csv"
US = {"NYSE", "NASDAQ", "NYSE ARCA", "NYSE MKT", "AMEX", "BATS"}
SLACK = pd.Timedelta(days=7)

report = pd.read_csv(YF_ONLY_REPORT)
missing = set(report.loc[report["status"] == "missing", "symbol"])
explicit = set(pd.read_csv(TICKER_MAP_FILE, comment="#")["index_ticker"])
st = pd.read_csv(TIINGO_LIST, parse_dates=["startDate", "endDate"])
st = st[st["exchange"].isin(US) & (st["priceCurrency"] == "USD")]
st["ticker"] = st["ticker"].str.upper()

raw = index_membership(pd.bdate_range(TRAIN[0], data_end()))
rows = []
for t in raw.columns:
    sym = t.replace(".", "-")
    if t in explicit or sym not in missing or not raw[t].any():
        continue
    on = raw.index[raw[t]]
    cand = st[st["ticker"] == sym]
    full = cand[(cand["startDate"] <= on.min() + SLACK) & (cand["endDate"] >= on.max() - SLACK)]
    if full.empty:
        rows.append((t, "", f"not on Tiingo for {on.min().date()}..{on.max().date()}"))
    else:
        note = "ambiguous: several Tiingo rows (validate)" if len(cand) > 1 else ""
        rows.append((t, f"ti_{sym}", note))

out = pd.DataFrame(rows, columns=["index_ticker", "entity", "note"])
out.insert(2, "start", "")
out.insert(3, "end", "")
OUT.write_text("# Generated by scripts/build_tiingo_map.py; data/ticker_map.csv takes precedence.\n")
out.to_csv(OUT, mode="a", index=False)
print(out["entity"].ne("").sum(), "mapped,", out["entity"].eq("").sum(), "unavailable")
print(out[out["note"] != ""].to_string())
